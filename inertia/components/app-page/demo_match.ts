function participant(line: Line): Participant {
  const [
    puuid,
    name,
    team,
    position,
    championId,
    [kills, deaths, assists],
    cs,
    gold,
    damage,
    taken,
    vision,
    objectives,
    level,
    items,
    spells,
    [primary, keystone, sub],
    [ad, ap, tr],
  ] = line
  return {
    puuid,
    gameName: name,
    tagLine: '',
    championId,
    teamId: team,
    win: team === 100,
    kills,
    deaths,
    assists,
    cs,
    level,
    champLevel: level,
    items,
    spells,
    perks: { primary, sub, keystone },
    visionScore: vision,
    damageTaken: taken,
    damageDealt: damage * 4,
    physicalDamageDealt: damage * 4 * ad,
    magicDamageDealt: damage * 4 * ap,
    trueDamageDealt: damage * 4 * tr,
    totalDamageDealtToChampions: damage,
    physicalDamageDealtToChampions: Math.round(damage * ad),
    magicDamageDealtToChampions: Math.round(damage * ap),
    trueDamageDealtToChampions: Math.round(damage * tr),
    damageDealtToObjectives: objectives,
    damageDealtToTurrets: Math.round(objectives * 0.4),
    totalMinionsKilled: position === 'JUNGLE' ? Math.round(cs * 0.2) : cs,
    neutralMinionsKilled: position === 'JUNGLE' ? Math.round(cs * 0.8) : 0,
    visionWardsBoughtInGame: position === 'UTILITY' ? 9 : position === 'JUNGLE' ? 6 : 2,
    position,
    goldEarned: gold,
    wardsPlaced: position === 'UTILITY' ? 31 : position === 'JUNGLE' ? 14 : 8,
    wardsKilled: position === 'UTILITY' ? 9 : 3,
    ...ZERO_PINGS,
    onMyWayPings: ((kills + assists) % 7) + 2,
    enemyMissingPings: deaths + 1,
    assistPings: 1,
  }
}

