"""Writes app/services/build_card_glyphs.ts: the glyphs the shared-build card draws
(`build_card.ts`) as SVG outlines, so the server needs no font. The build's name is the player's
own text, so the title face holds Latin (with its extensions, from Archivo) and Cyrillic (from
Geist, the site's Cyrillic face); a name with any other letter is not drawn (the card then titles
the build by its champion, and the page's meta tags keep the name).

    python3 -m pip install fonttools brotli
    python3 scripts/build_card_glyphs.py && npx eslint --fix app/services/build_card_glyphs.ts

Run it again after the fonts in vendor/invadelol-ui change, then bump RENDERER in build_card.ts.
"""
import json
import string
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'vendor/invadelol-ui/dist/fonts'
LATIN = FONTS / 'archivo-latin-wdth.woff2'
LATIN_EXT = FONTS / 'archivo-latin-ext-wdth.woff2'
CYRILLIC = FONTS / 'geist-cyrillic-wght-normal.woff2'
OUT = ROOT / 'app/services/build_card_glyphs.ts'

ASCII = ''.join(chr(c) for c in range(0x20, 0x7F))
LATIN1 = ''.join(chr(c) for c in range(0xA0, 0x180))  # Latin-1 supplement + Extended-A
CYR = ''.join(chr(c) for c in range(0x400, 0x460))
MARKS = '·–—’‘“”…'

FACES = {
    # The build's name, as the editor's title: 650.
    'title': (650, ASCII + LATIN1 + CYR + MARKS),
    # The champion, the role and the slot labels: 500 / 600.
    'label': (600, ASCII + LATIN1 + MARKS),
}


def outlines(path, weight, chars, out):
    font = TTFont(path)
    axes = {a.axisTag: a for a in font['fvar'].axes}
    pins = {'wght': weight}
    if 'wdth' in axes:
        pins['wdth'] = 100
    font = instantiateVariableFont(font, pins)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    scale = 1000 / font['head'].unitsPerEm
    for ch in chars:
        if ch in out or ord(ch) not in cmap:
            continue
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda n: f'{n * scale:.0f}')
        glyphs[name].draw(pen)
        out[ch] = [round(font['hmtx'][name][0] * scale), pen.getCommands()]
    return round(font['OS/2'].sCapHeight * scale)


faces = {}
for key, (weight, chars) in FACES.items():
    glyphs = {}
    cap = outlines(LATIN, weight, chars, glyphs)
    outlines(LATIN_EXT, weight, chars, glyphs)
    outlines(CYRILLIC, weight, chars, glyphs)
    faces[key] = {'units': 1000, 'capHeight': cap, 'glyphs': glyphs}

OUT.write_text(
    '// Generated by scripts/build_card_glyphs.py from Archivo and Geist (SIL Open Font License,\n'
    '// vendor/invadelol-ui/dist/fonts/OFL.txt). Each glyph: [advance, SVG path], font units, y up.\n'
    f'export const GLYPHS = {json.dumps(faces, ensure_ascii=False)} as const\n'
)
print(OUT, OUT.stat().st_size, {key: len(f['glyphs']) for key, f in faces.items()})
