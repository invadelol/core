"""Writes app/services/presence_glyphs.ts: the few Archivo glyphs the Discord presence picture
draws (digits, "/", ":", the role and length captions), as SVG outlines. The server then needs
no font, and the picture looks the same everywhere.

    python3 -m pip install fonttools brotli
    python3 scripts/presence_glyphs.py && npx eslint --fix app/services/presence_glyphs.ts
"""
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'vendor/invadelol-ui/dist/fonts/archivo-latin-wdth.woff2'
OUT = ROOT / 'app/services/presence_glyphs.ts'

# The app's figures (`.iv-dial b`: weight 750, width 92 %) and its small caps labels.
FACES = {
    'score': ({'wght': 760, 'wdth': 92}, '0123456789/: '),
    'caption': ({'wght': 640, 'wdth': 100}, '0123456789: ABDGIJLMNOPSTU'),
}


def face(axes, chars):
    font = instantiateVariableFont(TTFont(FONT), axes)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    out = {}
    for ch in chars:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda n: f'{round(n)}')
        glyphs[name].draw(pen)
        out[ch] = [font['hmtx'][name][0], pen.getCommands()]
    return {'units': font['head'].unitsPerEm, 'capHeight': font['OS/2'].sCapHeight, 'glyphs': out}


faces = {key: face(axes, chars) for key, (axes, chars) in FACES.items()}
OUT.write_text(
    '// Generated by scripts/presence_glyphs.py from Archivo (SIL Open Font License,\n'
    '// vendor/invadelol-ui/dist/fonts/OFL.txt). Each glyph: [advance, SVG path], font units, y up.\n'
    f'export const GLYPHS = {json.dumps(faces, ensure_ascii=False)} as const\n'
)
print(OUT, OUT.stat().st_size)
