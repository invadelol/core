"""Writes app/services/og/glyphs.ts: the heavy faces the link previews (`app/services/og/`) set
their names and figures in, as SVG outlines from Sofia Sans at 900, so the server needs no font.
Their labels use the share card's lighter faces (`share_card_glyphs.ts`). Names come from
players, so the display face holds Latin with its extensions, Greek and Cyrillic; a name with any
other letter is drawn without it.

    python3 -m pip install fonttools brotli
    python3 scripts/og_glyphs.py && npx prettier --write app/services/og/glyphs.ts

Run it again when the fonts change, then bump RENDERER in app/services/og/kit.ts.
"""
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'inertia/css/fonts/sofia-sans'
FILES = ['latin', 'latin-ext', 'greek', 'cyrillic', 'cyrillic-ext']
OUT = ROOT / 'app/services/og/glyphs.ts'

ASCII = ''.join(chr(c) for c in range(0x20, 0x7F))
EXT = ''.join(chr(c) for c in range(0xA0, 0x250))
GREEK = ''.join(chr(c) for c in range(0x370, 0x400))
CYR = ''.join(chr(c) for c in range(0x400, 0x530))
MARKS = '·’‘“”…–−'
TEXT = ASCII + EXT + GREEK + CYR + MARKS

FACES = {
    # Names and titles: 900.
    'display': (900, TEXT),
    # The big figures, proportional digits: 900.
    'figure': (900, ASCII + MARKS),
}


def tabular(font):
    out = {}
    if 'GSUB' not in font:
        return out
    for record in font['GSUB'].table.FeatureList.FeatureRecord:
        if record.FeatureTag != 'tnum':
            continue
        for index in record.Feature.LookupListIndex:
            for sub in font['GSUB'].table.LookupList.Lookup[index].SubTable:
                ext = getattr(sub, 'ExtSubTable', None)
                out.update(getattr(sub, 'mapping', None) or getattr(ext, 'mapping', None) or {})
    return out


def outlines(path, weight, chars, out):
    font = instantiateVariableFont(TTFont(path), {'wght': weight})
    glyphs, cmap, tnum = font.getGlyphSet(), font.getBestCmap(), tabular(font)
    scale = 1000 / font['head'].unitsPerEm
    for ch in chars:
        if ch in out or ord(ch) not in cmap:
            continue
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda n: f'{n * scale:.0f}')
        glyphs[name].draw(pen)
        out[ch] = [round(font['hmtx'][name][0] * scale), pen.getCommands()]
    return round(font['OS/2'].sCapHeight * scale)


faces = {}
for key, (weight, chars) in FACES.items():
    glyphs = {}
    cap = None
    for f in FILES:
        c = outlines(FONTS / f'sofia-sans-{f}-wght-normal.woff2', weight, chars, glyphs)
        cap = cap or c
    faces[key] = {'units': 1000, 'capHeight': cap, 'glyphs': glyphs}

OUT.write_text(
    '// Generated by scripts/og_glyphs.py from Sofia Sans (SIL Open Font License,\n'
    '// inertia/css/fonts/sofia-sans/OFL.txt). Each glyph: [advance, SVG path], font units, y up.\n'
    f'export const GLYPHS = {json.dumps(faces, ensure_ascii=False)} as const\n'
)
print(OUT, OUT.stat().st_size, {key: len(f['glyphs']) for key, f in faces.items()})
