"""Writes app/services/changelog_card_glyphs.ts: the Archivo glyphs the desktop app's version
image draws (`changelog_card.ts`, the link preview of /app/changelog/<version>), as SVG outlines.
The server then needs no font, and the image looks the same everywhere. It draws the version in
the figure style and the "Invade" of the lockup, nothing else.

    python3 -m pip install fonttools brotli
    python3 scripts/changelog_card_glyphs.py && npx eslint --fix app/services/changelog_card_glyphs.ts

Run it again after the fonts in vendor/invadelol-ui change, then bump RENDERER in
changelog_card.ts so shared images are drawn again.
"""
import json
import string
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'vendor/invadelol-ui/dist/fonts/archivo-latin-wdth.woff2'
OUT = ROOT / 'app/services/changelog_card_glyphs.ts'

FACES = {
    # `.iv-fig` (weight 700, width 92 %, tabular): the version, a pre-release's `-beta.1` included.
    'fig': ({'wght': 700, 'wdth': 92}, string.digits + '.-' + string.ascii_lowercase),
    # The lockup's word, as the Logo's `word` sets it: 600.
    'word': ({'wght': 600, 'wdth': 100}, 'Invade'),
}


def tabular(font):
    """The font's `tnum` substitutions: every figure on the site is tabular."""
    out = {}
    gsub = font['GSUB'].table
    for record in gsub.FeatureList.FeatureRecord:
        if record.FeatureTag != 'tnum':
            continue
        for index in record.Feature.LookupListIndex:
            for sub in gsub.LookupList.Lookup[index].SubTable:
                ext = getattr(sub, 'ExtSubTable', None)
                out.update(getattr(sub, 'mapping', None) or getattr(ext, 'mapping', None) or {})
    return out


def face(axes, chars):
    font = instantiateVariableFont(TTFont(FONT), axes)
    glyphs, cmap, tnum = font.getGlyphSet(), font.getBestCmap(), tabular(font)
    scale = 1000 / font['head'].unitsPerEm
    out = {}
    for ch in chars:
        if ch in out or ord(ch) not in cmap:
            continue
        name = cmap[ord(ch)]
        if ch.isdigit():
            name = tnum.get(name, name)
        pen = SVGPathPen(glyphs, ntos=lambda n: f'{n * scale:.0f}')
        glyphs[name].draw(pen)
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        top = round(bounds.bounds[3] * scale) if bounds.bounds else 0
        # [advance, path, top of the ink]
        out[ch] = [round(font['hmtx'][name][0] * scale), pen.getCommands(), top]
    hhea = font['hhea']
    return {
        'units': 1000,
        'capHeight': round(font['OS/2'].sCapHeight * scale),
        'ascent': round(hhea.ascent * scale),
        'descent': round(-hhea.descent * scale),
        'glyphs': out,
    }


faces = {key: face(axes, chars) for key, (axes, chars) in FACES.items()}
OUT.write_text(
    '// Generated by scripts/changelog_card_glyphs.py from Archivo (SIL Open Font License,\n'
    '// vendor/invadelol-ui/dist/fonts/OFL.txt). Each glyph: [advance, SVG path, ink top], font\n'
    '// units, y up.\n'
    f'export const GLYPHS = {json.dumps(faces, ensure_ascii=False)} as const\n'
)
print(OUT, OUT.stat().st_size, {key: len(f['glyphs']) for key, f in faces.items()})
