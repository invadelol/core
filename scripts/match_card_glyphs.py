"""Writes app/services/match_card_glyphs.ts: the Archivo glyphs the match share card draws
(`match_card.ts`), as SVG outlines at the site's own weights and widths, and the site's grain
(inertia/css/grain.png, which the server build does not ship). The server then needs no font and
reads no file, and the card looks the same everywhere. Only fixed words (the result, the queue,
MVP / ACE) and figures are drawn, so the faces hold letters, figures and a few marks: never a
player's name.

    python3 -m pip install fonttools brotli
    python3 scripts/match_card_glyphs.py && npx eslint --fix app/services/match_card_glyphs.ts

Run it again after the fonts in vendor/invadelol-ui change, or when the card draws a new word
whose letters are not here (`match_card.ts` skips a missing glyph), then bump RENDERER in
match_card.ts so shared images are drawn again.
"""
import base64
import json
import string
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'vendor/invadelol-ui/dist/fonts/archivo-latin-wdth.woff2'
OUT = ROOT / 'app/services/match_card_glyphs.ts'
GRAIN = ROOT / 'inertia/css/grain.png'

DIGITS = string.digits
LETTERS = string.ascii_letters
WORDS = LETTERS + DIGITS + " :/&-'()"

FACES = {
    # `.iv-fig`, the K/D/A: weight 700, width 92 %.
    'fig': ({'wght': 700, 'wdth': 92}, DIGITS),
    # The quiet slash of the match row's K/D/A, and the meta's separator dot (weight 400).
    'thin': ({'wght': 400, 'wdth': 100}, '/·'),
    # PerfDial's number: 750, normal width.
    'dial': ({'wght': 750, 'wdth': 100}, DIGITS),
    # The result ("Victory"), as the match header's title: 650.
    'title': ({'wght': 650, 'wdth': 100}, WORDS),
    # The queue and the length, as the row's meta: 500.
    'label': ({'wght': 500, 'wdth': 100}, WORDS + '·'),
    # PerfDial's placement (MVP, ACE): 700.
    'place': ({'wght': 700, 'wdth': 100}, string.ascii_uppercase + DIGITS),
}


def tabular(font):
    """The font's `tnum` substitutions: every figure on the site is tabular."""
    out = {}
    gsub = font['GSUB'].table
    for record in gsub.FeatureList.FeatureRecord:
        if record.FeatureTag != 'tnum':
            continue
        for index in record.Feature.LookupListIndex:
            for sub in gsub.LookupList.Lookup[index].SubTable:
                ext = getattr(sub, 'ExtSubTable', None)
                out.update(getattr(sub, 'mapping', None) or getattr(ext, 'mapping', None) or {})
    return out


def face(axes, chars):
    font = instantiateVariableFont(TTFont(FONT), axes)
    glyphs, cmap, tnum = font.getGlyphSet(), font.getBestCmap(), tabular(font)
    scale = 1000 / font['head'].unitsPerEm
    out = {}
    for ch in chars:
        if ch in out or ord(ch) not in cmap:
            continue
        name = cmap[ord(ch)]
        if ch.isdigit():
            name = tnum.get(name, name)
        pen = SVGPathPen(glyphs, ntos=lambda n: f'{n * scale:.0f}')
        glyphs[name].draw(pen)
        out[ch] = [round(font['hmtx'][name][0] * scale), pen.getCommands()]
    return {'units': 1000, 'capHeight': round(font['OS/2'].sCapHeight * scale), 'glyphs': out}


faces = {key: face(axes, chars) for key, (axes, chars) in FACES.items()}
OUT.write_text(
    '// Generated by scripts/match_card_glyphs.py from Archivo (SIL Open Font License,\n'
    '// vendor/invadelol-ui/dist/fonts/OFL.txt). Each glyph: [advance, SVG path], font units, y up.\n'
    f'export const GLYPHS = {json.dumps(faces, ensure_ascii=False)} as const\n\n'
    '/** The site\'s grain (inertia/css/grain.png, 128 by 128), tiled over the card. */\n'
    f"export const GRAIN_PNG = '{base64.b64encode(GRAIN.read_bytes()).decode()}'\n"
)
print(OUT, OUT.stat().st_size, {key: len(f['glyphs']) for key, f in faces.items()})
