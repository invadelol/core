"""Writes app/services/site_card_glyphs.ts: the glyphs the site's share cards draw (`site_card.ts`:
the home, a champion, a tier list, a stats view, the pros, a pro, a team) as SVG outlines, so the
server needs no font. Names (champions, pros, teams) come from the data, so the title and label
faces hold Latin (with its extensions, from Archivo) and Cyrillic (from Geist, the site's Cyrillic
face); a name with any other letter is drawn without it (`site_card.ts` skips a missing glyph).

    python3 -m pip install fonttools brotli
    python3 scripts/site_card_glyphs.py && npx prettier --write app/services/site_card_glyphs.ts

Run it again after the fonts in vendor/invadelol-ui change, then bump RENDERER in site_card.ts.
"""
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'vendor/invadelol-ui/dist/fonts'
LATIN = FONTS / 'archivo-latin-wdth.woff2'
LATIN_EXT = FONTS / 'archivo-latin-ext-wdth.woff2'
CYRILLIC = FONTS / 'geist-cyrillic-wght-normal.woff2'
OUT = ROOT / 'app/services/site_card_glyphs.ts'

ASCII = ''.join(chr(c) for c in range(0x20, 0x7F))
LATIN1 = ''.join(chr(c) for c in range(0xA0, 0x180))  # Latin-1 supplement + Extended-A
CYR = ''.join(chr(c) for c in range(0x400, 0x460))
MARKS = '·’‘“”…'

FACES = {
    # `.iv-fig`: the card's one figure (a win rate, LP, a count) and the tier marks: 700, width 92.
    'fig': (700, 92, '0123456789.,%+#SABCD'),
    # The title (a champion, a pro, a team, a page): 650.
    'title': (650, 100, ASCII + LATIN1 + CYR + MARKS),
    # The kicker and the labels: 500.
    'label': (500, 100, ASCII + LATIN1 + CYR + MARKS),
}


def tabular(font):
    """The font's `tnum` substitutions: every figure on the site is tabular."""
    out = {}
    if 'GSUB' not in font:
        return out
    gsub = font['GSUB'].table
    for record in gsub.FeatureList.FeatureRecord:
        if record.FeatureTag != 'tnum':
            continue
        for index in record.Feature.LookupListIndex:
            for sub in gsub.LookupList.Lookup[index].SubTable:
                ext = getattr(sub, 'ExtSubTable', None)
                out.update(getattr(sub, 'mapping', None) or getattr(ext, 'mapping', None) or {})
    return out


def outlines(path, weight, width, chars, out):
    font = TTFont(path)
    axes = {a.axisTag: a for a in font['fvar'].axes}
    pins = {'wght': weight}
    if 'wdth' in axes:
        pins['wdth'] = width
    font = instantiateVariableFont(font, pins)
    glyphs, cmap, tnum = font.getGlyphSet(), font.getBestCmap(), tabular(font)
    scale = 1000 / font['head'].unitsPerEm
    for ch in chars:
        if ch in out or ord(ch) not in cmap:
            continue
        name = cmap[ord(ch)]
        if ch.isdigit():
            name = tnum.get(name, name)
        pen = SVGPathPen(glyphs, ntos=lambda n: f'{n * scale:.0f}')
        glyphs[name].draw(pen)
        out[ch] = [round(font['hmtx'][name][0] * scale), pen.getCommands()]
    return round(font['OS/2'].sCapHeight * scale)


faces = {}
for key, (weight, width, chars) in FACES.items():
    glyphs = {}
    cap = outlines(LATIN, weight, width, chars, glyphs)
    outlines(LATIN_EXT, weight, width, chars, glyphs)
    outlines(CYRILLIC, weight, width, chars, glyphs)
    faces[key] = {'units': 1000, 'capHeight': cap, 'glyphs': glyphs}

OUT.write_text(
    '// Generated by scripts/site_card_glyphs.py from Archivo and Geist (SIL Open Font License,\n'
    '// vendor/invadelol-ui/dist/fonts/OFL.txt). Each glyph: [advance, SVG path], font units, y up.\n'
    f'export const GLYPHS = {json.dumps(faces, ensure_ascii=False)} as const\n'
)
print(OUT, OUT.stat().st_size, {key: len(f['glyphs']) for key, f in faces.items()})
